const CLASSIC_BY_ID: Record<string, Dish> = Object.fromEntries(DISHES.map((d) => [d.id, d]));

/**
 * The live catalogue (database, via /api/dishes) wins, so admin edits reach the
 * game; the classic entries only keep older saved meals readable.
 */
export function getDish(id: string | null | undefined): Dish | undefined {
  if (!id) return undefined;
  return getReelGameDish(id) ?? CLASSIC_BY_ID[id];
}
